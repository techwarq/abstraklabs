// normalise a display name ("Your bank", "QuickBooks") to a key
function keyFor(name: string): string {
  return name.toLowerCase().replace(/^your\s+/, "").replace(/\s+/g, "");
}

export function sourceColor(name: string): string {
  const k = keyFor(name);
  if (BRANDS[k]) return BRANDS[k].color;
  if (k === "bank") return "#64748B";
  return "#8B6D4E"; // inventory / fallback
}

export function SourceLogo({ name, size = 18 }: { name: string; size?: number }) {
  const k = keyFor(name);
  const brand = BRANDS[k];

  if (brand) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill={brand.color} aria-hidden="true">
        <path d={brand.path} />
      </svg>
    );
  }

  if (k === "bank") {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="#64748B" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
        <path d="M3 10l9-6 9 6" />
        <path d="M5 10v8M9.5 10v8M14.5 10v8M19 10v8" />
        <path d="M3 21h18" />
      </svg>
    );
  }

  // inventory / catalog
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="#8B6D4E" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      <path d="M21 8l-9-5-9 5 9 5 9-5z" />
      <path d="M3 8v8l9 5 9-5V8" />
      <path d="M12 13v8" />
    </svg>
  );
}

